"""Publish reviewed skill folders for Codex's built-in GitHub skill installer."""
import argparse
import hashlib
import io
import json
from pathlib import Path
import re
import subprocess
import tarfile

from bridge import reviewed_payloads
from skills import ROOT, safe_path

EXPORT = ROOT / 'installables/codex'
REGISTRY = ROOT / 'site/dist/codex-installer.json'
PREFIX = 'installables/codex/'
REPO = 'Cold-ay/AI-Skills-Library'


def export(reviewed=False, destination=EXPORT):
    if not reviewed:
        raise ValueError('Review source packages before passing --reviewed')
    entries, combos, singles, groups = reviewed_payloads()
    files = {}; records = []
    for kind, records_by_id, payloads in [('skill', entries, singles), ('combination', combos, groups)]:
        for ident, payload in sorted(payloads.items()):
            record = records_by_id[ident]
            folders = [ident] if kind == 'skill' else list(record['skills']) + ['combination-' + ident]
            for path, content in payload.items():
                path = 'skills/' + path; safe_path(path)
                if path in files and files[path] != content:
                    raise ValueError('Conflicting exported skill versions')
                files[path] = content
            records.append(dict(kind=kind, id=ident, title=record.get('title') or ident,
                                invocation=record['invocation'] if kind == 'skill' else 'combination-' + ident,
                                folders=folders, paths=[PREFIX + 'skills/' + f for f in folders]))
    files['README.md'] = (
        '# Codex installer distribution\n\n'
        'Generated by codex_export.py from reviewed, pinned download packs. Each skills/<name>/ '
        'folder contains SKILL.md and the supporting files/licenses needed for file installation. '
        'Original upstream files are unchanged. The five combination wrappers are library-authored.\n\n'
        'Use Codex $skill-installer with a full commit ref and the paths in index.json. '
        'For a combination, install every listed member and its wrapper into the same skills root. '
        'Check ALL destination folders before starting: the built-in installer copies sequentially, '
        'does not resolve dependencies and does not promise transactional rollback. '
        'Do not overwrite existing skills. Runtime dependencies require separate setup; '
        'copying files does not run upstream scripts or validate agent behavior.\n\n'
        'index.json records source pins, workflows and SHA-256 file checksums. The website registry '
        'pins a committed version of this distribution; no mutable branch ref is required.\n'
    ).encode()
    index = dict(version=1, repo=REPO, entries=records,
                 sources=[entries[i] for i in sorted(singles)],
                 workflows=[combos[i] for i in sorted(groups)],
                 files={p: hashlib.sha256(b).hexdigest() for p, b in sorted(files.items())})
    destination = Path(destination)
    if destination.exists():
        previous = json.loads((destination / 'index.json').read_text())
        expected = set(previous['files']) | {'index.json'}
        actual = {p.relative_to(destination).as_posix() for p in destination.rglob('*') if p.is_file() or p.is_symlink()}
        if actual != expected:
            raise ValueError('Unmanaged files in generated distribution; refusing to replace them')
        for path, digest in previous['files'].items():
            safe_path(path)
            target = destination / path
            if target.is_symlink() or hashlib.sha256(target.read_bytes()).hexdigest() != digest:
                raise ValueError('Edited generated files; preserve changes before rebuilding')
        for path in set(previous['files']) - set(files):
            (destination / path).unlink()
    destination.mkdir(parents=True, exist_ok=True)
    for path, content in files.items():
        target = destination / path; target.parent.mkdir(parents=True, exist_ok=True); target.write_bytes(content)
    (destination / 'index.json').write_text(json.dumps(index, indent=2) + '\n')
    return index


def committed_export(ref):
    if not re.fullmatch(r'[0-9a-f]{40}', ref):
        raise ValueError('Use an immutable full Git commit SHA')
    archive = subprocess.check_output(['git', 'archive', ref, PREFIX.rstrip('/')], cwd=ROOT)
    with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
        files = {}
        for item in tar:
            if item.isdir():
                continue
            if not item.isfile() or not item.name.startswith(PREFIX):
                raise ValueError('Unsupported committed export member')
            path = item.name[len(PREFIX):]; safe_path(path)
            files[path] = tar.extractfile(item).read()
    index = json.loads(files['index.json'])
    if set(files) != set(index['files']) | {'index.json'}:
        raise ValueError('Committed export inventory mismatch')
    for path, digest in index['files'].items():
        if hashlib.sha256(files[path]).hexdigest() != digest:
            raise ValueError('Committed export integrity mismatch')
    return index, files


def publish(ref):
    index, files = committed_export(ref)
    # Do not accidentally publish metadata for an older/different local tree.
    for path, content in files.items():
        if (EXPORT / path).read_bytes() != content:
            raise ValueError('Local distribution differs from the requested commit')
    registry = dict(version=1, repo=REPO, ref=ref, entries=index['entries'],
                    index_sha256=hashlib.sha256(files['index.json']).hexdigest())
    REGISTRY.write_text(json.dumps(registry, indent=2) + '\n')
    return registry


def validate_registry():
    registry = json.loads(REGISTRY.read_text())
    index = json.loads((EXPORT / 'index.json').read_text())
    if registry.get('version') != 1 or registry.get('repo') != REPO or not re.fullmatch(r'[0-9a-f]{40}', registry.get('ref', '')):
        raise ValueError('Invalid Codex installer registry')
    if registry['entries'] != index['entries'] or registry['index_sha256'] != hashlib.sha256((EXPORT / 'index.json').read_bytes()).hexdigest():
        raise ValueError('Codex installer registry is stale; publish the committed export again')
    for path, digest in index['files'].items():
        safe_path(path)
        if hashlib.sha256((EXPORT / path).read_bytes()).hexdigest() != digest:
            raise ValueError('Codex export file differs from registry')
    return registry


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reviewed', action='store_true')
    parser.add_argument('--publish-ref')
    args = parser.parse_args()
    try:
        result = publish(args.publish_ref) if args.publish_ref else export(args.reviewed)
        print('Published pinned registry' if args.publish_ref else 'Exported reviewed folders', len(result['entries']))
    except (ValueError, KeyError, OSError, subprocess.CalledProcessError) as exc:
        parser.exit(1, 'Error: ' + str(exc) + '\n')
